-- Experiment status enum
DO $$ BEGIN
  CREATE TYPE public.experiment_status AS ENUM ('draft','running','paused','completed','archived');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- experiments
CREATE TABLE IF NOT EXISTS public.experiments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  key text NOT NULL UNIQUE,
  name text NOT NULL,
  description text,
  status public.experiment_status NOT NULL DEFAULT 'draft',
  traffic_allocation numeric NOT NULL DEFAULT 1.0 CHECK (traffic_allocation >= 0 AND traffic_allocation <= 1),
  primary_metric text,
  audience_rules jsonb NOT NULL DEFAULT '{}'::jsonb,
  started_at timestamptz,
  ended_at timestamptz,
  created_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT ON public.experiments TO authenticated, anon;
GRANT ALL ON public.experiments TO service_role;
ALTER TABLE public.experiments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "experiments readable by all" ON public.experiments FOR SELECT USING (true);
CREATE POLICY "experiments admin write" ON public.experiments FOR ALL TO authenticated
  USING (public.has_role(auth.uid(),'admin')) WITH CHECK (public.has_role(auth.uid(),'admin'));

