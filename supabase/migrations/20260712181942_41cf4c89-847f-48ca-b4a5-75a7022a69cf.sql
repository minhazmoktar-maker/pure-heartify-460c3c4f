CREATE OR REPLACE FUNCTION public.evaluate_feature_flag(_key text, _user_id uuid)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  f RECORD;
  bucket int;
BEGIN
  SELECT * INTO f FROM public.feature_flags WHERE key = _key;
  IF NOT FOUND THEN RETURN false; END IF;
  IF f.kill_switch THEN RETURN false; END IF;
  IF NOT f.enabled THEN RETURN false; END IF;
  IF f.cohort_id IS NOT NULL THEN
    IF _user_id IS NULL OR NOT public.is_in_cohort(_user_id, f.cohort_id) THEN
      RETURN false;
    END IF;
  END IF;
  IF f.rollout_percent >= 100 THEN RETURN true; END IF;
  IF f.rollout_percent <= 0 THEN RETURN false; END IF;
  bucket := abs(hashtext(_key || COALESCE(_user_id::text, ''))) % 100;
  RETURN bucket < f.rollout_percent;
END $$;

-- ============================================================
-- Sticky assignment RPC
-- ============================================================
CREATE OR REPLACE FUNCTION public.assign_experiment_variant(_experiment_key text, _anon_key text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  exp RECORD;
  existing text;
  chosen text;
  bucket numeric;
  cum numeric := 0;
  v RECORD;
  uid uuid := auth.uid();
  seed text;
BEGIN
  SELECT * INTO exp FROM public.experiments WHERE key = _experiment_key AND status = 'running';
  IF NOT FOUND THEN RETURN NULL; END IF;

  IF uid IS NOT NULL THEN
    SELECT variant_key INTO existing FROM public.variant_assignments
      WHERE experiment_id = exp.id AND user_id = uid;
  ELSIF _anon_key IS NOT NULL THEN
    SELECT variant_key INTO existing FROM public.variant_assignments
      WHERE experiment_id = exp.id AND anon_key = _anon_key;
  END IF;
  IF existing IS NOT NULL THEN RETURN existing; END IF;

  seed := COALESCE(uid::text, _anon_key, gen_random_uuid()::text);
  -- traffic allocation gate
  IF (abs(hashtext(exp.key || ':traffic:' || seed)) % 10000) / 10000.0 > exp.traffic_allocation THEN
    RETURN NULL;
  END IF;

  bucket := (abs(hashtext(exp.key || ':' || seed)) % 10000) / 10000.0;
  FOR v IN SELECT key, weight FROM public.experiment_variants WHERE experiment_id = exp.id ORDER BY key LOOP
    cum := cum + v.weight;
    IF bucket < cum THEN chosen := v.key; EXIT; END IF;
  END LOOP;
  IF chosen IS NULL THEN
    SELECT key INTO chosen FROM public.experiment_variants WHERE experiment_id = exp.id ORDER BY key LIMIT 1;
  END IF;
  IF chosen IS NULL THEN RETURN NULL; END IF;

  INSERT INTO public.variant_assignments(experiment_id, user_id, anon_key, variant_key)
  VALUES (exp.id, uid, CASE WHEN uid IS NULL THEN _anon_key ELSE NULL END, chosen)
  ON CONFLICT DO NOTHING;

  RETURN chosen;
END $$;

GRANT EXECUTE ON FUNCTION public.assign_experiment_variant(text,text) TO authenticated, anon;
GRANT EXECUTE ON FUNCTION public.evaluate_feature_flag(text,uuid) TO authenticated, anon;

