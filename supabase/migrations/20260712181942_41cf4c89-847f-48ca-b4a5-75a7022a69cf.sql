-- Validation trigger on analytics_events
CREATE OR REPLACE FUNCTION public.validate_analytics_event()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  sch RECORD;
  req text;
BEGIN
  SELECT * INTO sch FROM public.event_schemas WHERE event_name = NEW.event_name AND is_active = true;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'unknown_event: %', NEW.event_name USING ERRCODE = 'check_violation';
  END IF;
  IF array_length(sch.required_properties, 1) IS NOT NULL THEN
    FOREACH req IN ARRAY sch.required_properties LOOP
      IF NEW.properties IS NULL OR NOT (NEW.properties ? req) THEN
        RAISE EXCEPTION 'missing_required_property: % for event %', req, NEW.event_name USING ERRCODE = 'check_violation';
      END IF;
    END LOOP;
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_validate_analytics_event ON public.analytics_events;
CREATE TRIGGER trg_validate_analytics_event
  BEFORE INSERT ON public.analytics_events
  FOR EACH ROW EXECUTE FUNCTION public.validate_analytics_event();

