CREATE OR REPLACE VIEW public.admin_experiment_results
WITH (security_invoker = true) AS
SELECT
  e.id AS experiment_id,
  e.key AS experiment_key,
  e.status,
  ex.variant_key,
  count(*) AS exposures,
  count(DISTINCT COALESCE(ex.user_id::text, ex.anon_key)) AS unique_users
FROM public.experiments e
JOIN public.experiment_exposures ex ON ex.experiment_id = e.id
GROUP BY e.id, e.key, e.status, ex.variant_key;

GRANT SELECT ON public.admin_experiment_results TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_retention_cohorts()
RETURNS TABLE (
  cohort_week date,
  cohort_size bigint,
  d1 bigint,
  d7 bigint,
  d30 bigint
) LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, auth AS $$
  WITH signups AS (
    SELECT u.id, date_trunc('week', u.created_at)::date AS cohort_week, u.created_at
    FROM auth.users u
    WHERE u.created_at > now() - interval '180 days'
  ),
  activity AS (
    SELECT user_id, date(created_at) AS d FROM public.analytics_events
    WHERE user_id IS NOT NULL AND created_at > now() - interval '210 days'
    GROUP BY user_id, date(created_at)
  )
  SELECT
    s.cohort_week,
    count(DISTINCT s.id) AS cohort_size,
    count(DISTINCT s.id) FILTER (WHERE a.d = date(s.created_at) + 1) AS d1,
    count(DISTINCT s.id) FILTER (WHERE a.d BETWEEN date(s.created_at) + 6 AND date(s.created_at) + 8) AS d7,
    count(DISTINCT s.id) FILTER (WHERE a.d BETWEEN date(s.created_at) + 28 AND date(s.created_at) + 32) AS d30
  FROM signups s
  LEFT JOIN activity a ON a.user_id = s.id
  GROUP BY s.cohort_week
  ORDER BY s.cohort_week DESC
$$;

REVOKE ALL ON FUNCTION public.admin_retention_cohorts() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_retention_cohorts() TO authenticated;

-- Wrap with admin check
CREATE OR REPLACE FUNCTION public.get_retention_cohorts()
RETURNS TABLE (cohort_week date, cohort_size bigint, d1 bigint, d7 bigint, d30 bigint)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.has_role(auth.uid(),'admin') THEN
    RAISE EXCEPTION 'forbidden';
  END IF;
  RETURN QUERY SELECT * FROM public.admin_retention_cohorts();
END $$;

GRANT EXECUTE ON FUNCTION public.get_retention_cohorts() TO authenticated;

