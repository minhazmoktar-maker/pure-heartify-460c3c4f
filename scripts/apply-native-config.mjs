#!/usr/bin/env node
/**
 * Heartify — native store configuration applier.
 *
 * `npx cap add ios|android` generates vanilla native shells. Everything the
 * stores require on top of that (release signing, target API level, permission
 * strings, privacy manifest, per-app languages) lives here so it is versioned
 * in the repo and re-applied idempotently after every `cap add` / `cap sync`.
 *
 *   node scripts/apply-native-config.mjs        # patch whatever exists
 *   node scripts/apply-native-config.mjs --check # verify only (CI gate)
 *
 * Missing platforms are skipped with a notice — this script never fails just
 * because a platform has not been added on this machine.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const ROOT = process.cwd();
const CHECK_ONLY = process.argv.includes('--check');

/** Play requires target API 35+ for new/updated apps in 2026. */
export const ANDROID_SDK = { compileSdk: 36, targetSdk: 36, minSdk: 24 };

const problems = [];
const changes = [];
const skipped = [];

const read = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : null);

function write(path, next, label) {
  const current = read(path);
  if (current === next) return;
  if (CHECK_ONLY) {
    problems.push(`${label} is out of date (${path})`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, next, 'utf8');
  changes.push(`${label} → ${path}`);
}

/* ────────────────────────────── Android ────────────────────────────── */

/**
 * Release signing reads from env vars / `android/keystore.properties` so no
 * secret ever lands in git. Play App Signing then re-signs the AAB.
 */
export const SIGNING_GRADLE = `// Generated by scripts/apply-native-config.mjs — do not edit by hand.
// Release signing for the Heartify upload key.
//
// Provide credentials either via android/keystore.properties (git-ignored):
//   storeFile=/absolute/path/upload-keystore.jks
//   storePassword=…
//   keyAlias=heartify
//   keyPassword=…
// or via env vars ANDROID_KEYSTORE_PATH / ANDROID_KEYSTORE_PASSWORD /
// ANDROID_KEY_ALIAS / ANDROID_KEY_PASSWORD (used by fastlane in CI).
def keystorePropsFile = rootProject.file("keystore.properties")
def keystoreProps = new Properties()
if (keystorePropsFile.exists()) {
    keystoreProps.load(new FileInputStream(keystorePropsFile))
}

ext.heartifySigning = [
    storeFile    : keystoreProps['storeFile'] ?: System.getenv('ANDROID_KEYSTORE_PATH'),
    storePassword: keystoreProps['storePassword'] ?: System.getenv('ANDROID_KEYSTORE_PASSWORD'),
    keyAlias     : keystoreProps['keyAlias'] ?: System.getenv('ANDROID_KEY_ALIAS'),
    keyPassword  : keystoreProps['keyPassword'] ?: System.getenv('ANDROID_KEY_PASSWORD'),
]

android {
    signingConfigs {
        release {
            if (heartifySigning.storeFile) {
                storeFile file(heartifySigning.storeFile)
                storePassword heartifySigning.storePassword
                keyAlias heartifySigning.keyAlias
                keyPassword heartifySigning.keyPassword
            }
        }
    }
    buildTypes {
        release {
            if (heartifySigning.storeFile) {
                signingConfig signingConfigs.release
            }
            minifyEnabled true
            shrinkResources true
            proguardFiles getDefaultProguardFile('proguard-android-optimize.txt'), 'proguard-rules.pro'
        }
    }
    bundle {
        language { enableSplit = false } // per-app languages must stay in the AAB
    }
}
`;

/**
 * Only the permissions Heartify actually uses. Every extra permission is a
 * Data-Safety mismatch and a review rejection risk.
 */
export const ANDROID_PERMISSIONS = [
  'android.permission.INTERNET',
  'android.permission.ACCESS_NETWORK_STATE',
  'android.permission.POST_NOTIFICATIONS',
  'android.permission.ACCESS_COARSE_LOCATION',
  'android.permission.ACCESS_FINE_LOCATION',
  'android.permission.VIBRATE',
  'com.android.vending.BILLING',
];

function patchAndroid() {
  const dir = join(ROOT, 'android');
  const appGradle = join(dir, 'app', 'build.gradle');
  const manifest = join(dir, 'app', 'src', 'main', 'AndroidManifest.xml');

  write(join(dir, 'app', 'heartify-signing.gradle'), SIGNING_GRADLE, 'Android release signing');

  const gradle = read(appGradle);
  if (!gradle) {
    skipped.push('android/app/build.gradle not found — run `npx cap add android` first');
  } else {
    let next = gradle
      .replace(/compileSdk\s+\w+/g, `compileSdk ${ANDROID_SDK.compileSdk}`)
      .replace(/targetSdkVersion\s+\S+/g, `targetSdkVersion ${ANDROID_SDK.targetSdk}`)
      .replace(/minSdkVersion\s+\S+/g, `minSdkVersion ${ANDROID_SDK.minSdk}`);
    if (!next.includes('heartify-signing.gradle')) {
      next += `\napply from: "heartify-signing.gradle"\n`;
    }
    write(appGradle, next, 'Android build.gradle (SDK levels + signing)');
  }

  const xml = read(manifest);
  if (!xml) {
    skipped.push('AndroidManifest.xml not found — run `npx cap add android` first');
  } else {
    let next = xml;
    for (const perm of ANDROID_PERMISSIONS) {
      if (!next.includes(`"${perm}"`)) {
        next = next.replace(
          '</manifest>',
          `    <uses-permission android:name="${perm}" />\n</manifest>`,
        );
      }
    }
    if (!next.includes('android:localeConfig')) {
      next = next.replace(
        /<application\b/,
        '<application android:localeConfig="@xml/locales_config"',
      );
    }
    write(manifest, next, 'AndroidManifest (permissions + localeConfig)');
  }
}

/* ──────────────────────────────── iOS ─────────────────────────────── */

export const IOS_USAGE_STRINGS = {
  NSUserNotificationsUsageDescription:
    'Heartify sends prayer time reminders and streak alerts. You can turn them off anytime in Settings.',
  NSLocationWhenInUseUsageDescription:
    'Heartify uses your location only to calculate accurate prayer times and Qibla direction. It is never sold or shared.',
};

function patchIos() {
  const plist = join(ROOT, 'ios', 'App', 'App', 'Info.plist');
  const privacy = join(ROOT, 'ios', 'App', 'App', 'PrivacyInfo.xcprivacy');
  const template = read(join(ROOT, 'docs', 'privacy-info.xcprivacy'));

  if (template) write(privacy, template, 'iOS privacy manifest');

  const current = read(plist);
  if (!current) {
    skipped.push('ios/App/App/Info.plist not found — run `npx cap add ios` first');
    return;
  }
  let next = current;
  for (const [key, value] of Object.entries(IOS_USAGE_STRINGS)) {
    if (!next.includes(`<key>${key}</key>`)) {
      next = next.replace(
        /<\/dict>\s*<\/plist>\s*$/,
        `\t<key>${key}</key>\n\t<string>${value}</string>\n</dict>\n</plist>\n`,
      );
    }
  }
  if (!next.includes('ITSAppUsesNonExemptEncryption')) {
    next = next.replace(
      /<\/dict>\s*<\/plist>\s*$/,
      '\t<key>ITSAppUsesNonExemptEncryption</key>\n\t<false/>\n</dict>\n</plist>\n',
    );
  }
  write(plist, next, 'Info.plist (usage strings + encryption declaration)');
}

/* ─────────────────────────────── run ─────────────────────────────── */

if (process.argv[1] && process.argv[1].endsWith('apply-native-config.mjs')) {
  patchAndroid();
  patchIos();

  for (const s of skipped) console.log(`• skipped: ${s}`);
  for (const c of changes) console.log(`✓ ${c}`);

  if (problems.length) {
    console.error('\n✗ native store config drift:');
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }
  console.log(
    changes.length ? '\n✓ native store config applied' : '\n✓ native store config already current',
  );
}
